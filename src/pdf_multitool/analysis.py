def _structured_options(options, markdown):
    if options is None:
        options = {}
    allowed = {"skip_repeated_margins", "reading_order"}
    if markdown:
        allowed.add("include_images")
    if not isinstance(options, dict) or set(options) - allowed:
        raise ValueError("Unsupported structured export options")
    validate_reading_order(options.get("reading_order", "auto"))
    if any(not isinstance(v, bool) for k, v in options.items() if k != "reading_order"):
        raise ValueError("Structured export options must be boolean")
    return options


def _markdown_escape(text):
    # Literal PDF text must not become Markdown links, images, HTML or math.
    text = text.replace("&", "&amp;")
    return re.sub(r"([\\`*_{}\[\]<>()#+.!|~$^\-])", r"\\\1", text)


def _line_runs(line, stats):
    """Source spans with conservative script tags and geometry-derived spaces."""
    spans = line.get("spans", [])
    biggest = max((_number(s.get("size"), 11) for s in spans), default=11)
    baselines = [
        _number(s.get("origin", (0, 0))[1])
        for s in spans
        if _number(s.get("size"), 11) >= biggest * 0.9 and s.get("text", "").strip()
    ]
    baseline = median(baselines) if baselines else 0
    horizontal = abs(_number(line.get("dir", (1, 0))[1])) < 0.1
    previous = None
    for span in spans:
        text = _clean(span.get("text", ""))
        if not text:
            continue
        size = _number(span.get("size"), 11)
        flags = int(span.get("flags", 0))
        kind = None
        if flags & 1:
            kind = "sup"
            stats["superscript_flag_spans"] += 1
        elif horizontal and size <= biggest * 0.85 and baseline:
            delta = _number(span.get("origin", (0, baseline))[1]) - baseline
            if delta >= biggest * 0.16:
                kind = "sub"
            elif delta <= -biggest * 0.18:
                kind = "sup"
            if kind:
                stats["geometry_inferred_script_spans"] += 1
        space = ""
        if previous is not None and horizontal and not kind:
            gap = _number(span.get("bbox", [0] * 4)[0]) - _number(previous.get("bbox", [0] * 4)[2])
            if (
                gap > min(size, _number(previous.get("size"), size)) * 0.2
                and not text[0].isspace()
                and not str(previous.get("text", " "))[-1:].isspace()
            ):
                space = " "
                stats["geometry_inserted_spaces"] += 1
        yield span, text, kind, space
        previous = span


def _render_structured_line(line, stats, markdown):
    pieces = []
    for span, text, kind, space in _line_runs(line, stats):
        if not markdown:
            pieces.append(space + text)
            continue
        # Keep whitespace outside emphasis delimiters so CommonMark renders it.
        leading = text[: len(text) - len(text.lstrip())]
        trailing = text[len(text.rstrip()) :]
        content = text.strip()
        if not content:
            pieces.append(space + text)
            continue
        flags = int(span.get("flags", 0))
        if kind or flags & 8:
            # CommonMark still parses Markdown inside inline HTML such as <sup>.
            # Encode ASCII punctuation as character references so literal source
            # links/images cannot become active nodes in downstream renderers.
            rendered = "".join(f"&#{ord(c)};" if c in punctuation else c for c in content)
            if flags & 8:
                rendered = "<code>" + rendered + "</code>"
            if flags & 16:
                rendered = "<strong>" + rendered + "</strong>"
            if flags & 2:
                rendered = "<em>" + rendered + "</em>"
            if kind:
                rendered = f"<{kind}>" + rendered + f"</{kind}>"
        else:
            rendered = _markdown_escape(content)
            marker = (
                "***"
                if flags & 16 and flags & 2
                else "**"
                if flags & 16
                else "*"
                if flags & 2
                else ""
            )
            rendered = marker + rendered + marker
        pieces.append(space + leading + rendered + trailing)
    return "".join(pieces).strip()


def _line_size(line):
    return _weighted_median(
        [
            (_number(s.get("size"), 11), len(_clean(s.get("text", ""))))
            for s in line.get("spans", [])
        ]
    )


def _paragraph_continues(previous, current, block):
    """Join clearly wrapped prose, never remove a hyphen or infer missing text."""
    ptext, ctext = _line_text(previous).rstrip(), _line_text(current).lstrip()
    if not ptext or not ctext or ptext.endswith(("-", "\u00ad", "\u2010", "\u2011")):
        return False
    # Keep list labels, equations and tabular spacing on their source lines.
    marker = r"^(?:[-*+\u2022\u25aa\u25e6]|\d+[.)]|\(?[A-Za-z][.)])\s"
    if re.match(marker, ptext) or re.match(marker, ctext):
        return False
    if any(re.search(r"\t| {3,}|[=≤≥≠∑∫]", text) for text in (ptext, ctext)):
        return False
    for line in (previous, current):
        direction = line.get("dir", (1, 0))
        if _number(direction[0]) < 0.9 or abs(_number(direction[1])) > 0.1 or line.get("wmode", 0):
            return False
        spans = line.get("spans", [])
        if any(int(span.get("flags", 0)) & 8 for span in spans):
            return False
        if any(
            _number(b.get("bbox", [0] * 4)[0]) - _number(a.get("bbox", [0] * 4)[2])
            > max(_number(a.get("size"), 11), _number(b.get("size"), 11))
            for a, b in itertools.pairwise(spans)
        ):
            return False
    p, c, b = _bbox(previous.get("bbox")), _bbox(current.get("bbox")), _bbox(block.get("bbox"))
    size, next_size = _line_size(previous), _line_size(current)
    if abs(size - next_size) > max(size, next_size) * 0.12:
        return False
    # Bounding boxes include ascenders/descenders, and may overlap a little.
    step = c[1] - p[1]
    width = max(0, b[2] - b[0])
    return (
        size * 0.65 <= step <= size * 1.9
        and abs(c[0] - b[0]) <= size * 0.65
        and abs(p[0] - c[0]) <= size * 1.8
        and b[2] - p[2] <= max(size * 2.7, width * 0.12)
    )


def _page_label(info):
    label = f"Source page {info['page']}"
    if info.get("page_label") and info["page_label"] != str(info["page"]):
        label += " (PDF label: " + info["page_label"] + ")"
    return label


def _structured_export(doc, out_path, original_name, options, markdown):
    options = _structured_options(options, markdown)
    reading_order = options.get("reading_order", "auto")
    include_images = options.get("include_images", True) if markdown else False
    skip_margins = options.get("skip_repeated_margins", False)
    analysis = analyze_document(doc, original_name)
    headings = analysis["heading_candidates"]
    heading_by_key = {_line_key(h["page"], h["bbox"], h["text"]): h for h in headings if h["bbox"]}
    margin_keys = {
        (o["page"], tuple(o["bbox"]))
        for candidate in analysis["repeated_header_footer_candidates"]
        for o in candidate["occurrences"]
    }
    warnings = list(dict.fromkeys(analysis["warnings"] + _STRUCTURED_WARNINGS))
    warnings.extend(_order_warning(reading_order))
    if markdown:
        warnings.extend(
            [
                (
                    "Source fonts and colors are not reproduced; bold and italic flags"
                    " are retained where available."
                ),
                (
                    "Superscript and subscript use safe inline HTML; reader support "
                    "varies and geometry-based inferences may be uncertain."
                ),
                (
                    "Raster images use sibling PNG/JPEG files. Keep the Markdown file "
                    "and its generated assets together."
                ),
                (
                    "Image clipping, masks, placement, rotation and blending may "
                    "differ from the source."
                ),
            ]
        )
    else:
        warnings.extend(
            [
                (
                    "Plain text cannot represent font style or baseline offsets; "
                    "original Unicode characters are retained without inventing "
                    "superscript/subscript characters."
                ),
                (
                    "Raster images are omitted from plain text; text inside those "
                    "images is not transcribed."
                ),
            ]
        )
    output = Path(out_path)
    kind = "markdown" if markdown else "text"
    outputs = [{"path": str(output), "name": output.name, "kind": kind}]
    asset_dir = None
    stats = Counter()
    emitted_anchors = set()
    with output.open("w", encoding="utf-8", newline="\n") as stream:
        if markdown:
            title = analysis["document_title"] or analysis["original_filename"]
            stream.write("# " + _markdown_escape(title) + "\n\n")
            stream.write("## Export navigation\n\nSource pages:\n\n")
            for info in analysis["pages"]:
                stream.write(f"- [{_markdown_escape(_page_label(info))}](#page-{info['page']})\n")
            if headings:
                stream.write("\nHeading candidates from the source:\n\n")
                for h in headings:
                    stream.write(
                        f"- [{_markdown_escape(h['text'])}](#{h['anchor']}) (page {h['page']}"
                        f", level {h['level']})\n"
                    )
            stream.write("\n")
        for page_index, page in enumerate(doc):
            page_num = page_index + 1
            info = analysis["pages"][page_index]
            label = _page_label(info)
            if markdown:
                stream.write(f'<a id="page-{page_num}"></a>\n\n## {_markdown_escape(label)}\n\n')
                for h in headings:
                    if h["page"] == page_num and h["bbox"] is None:
                        stream.write(f'<a id="{h["anchor"]}"></a>\n')
                        emitted_anchors.add(h["anchor"])
            else:
                stream.write("[" + label + "]\n\n")
            for block in _ordered_blocks(page, include_images, reading_order):
                if block.get("type") == 1:
                    if not include_images:
                        continue
                    stats["image_occurrences_seen"] += 1
                    try:
                        raw, extension = _image_payload(block, portable=True)
                    except (ValueError, RuntimeError, TypeError) as exc:
                        stats["image_occurrences_failed"] += 1
                        warnings.append(
                            f"Page {page_num}: one image could not be exported ("
                            f"{type(exc).__name__})."
                        )
                        stream.write("[Export note: one source image could not be exported.]\n\n")
                        continue
                    if asset_dir is None:
                        safe_stem = re.sub(r"[^A-Za-z0-9_-]", "_", output.stem)[:60] or "document"
                        asset_dir = Path(
                            tempfile.mkdtemp(prefix=safe_stem + "_assets_", dir=str(output.parent))
                        )
                    image_name = (
                        f"page-{page_num:04d}-image-{stats['images_exported'] + 1:04d}.{extension}"
                    )
                    asset = asset_dir / image_name
                    asset.write_bytes(raw)
                    relative = asset.relative_to(output.parent).as_posix()
                    outputs.append({"path": str(asset), "name": relative, "kind": "image"})
                    stats["images_exported"] += 1
                    stream.write(
                        f"![Extracted source image {stats['images_exported']}, page {page_num}]("
                        f"{relative})\n\n"
                    )
                    continue
                paragraph = []
                previous = None

                def flush(paragraph=paragraph):
                    if paragraph:
                        stream.write(" ".join(paragraph) + "\n\n")
                        paragraph.clear()

                for line in block.get("lines", []):
                    text = _line_text(line)
                    if not text.strip():
                        flush()
                        previous = None
                        continue
                    bbox = _bbox(line.get("bbox"))
                    margin = (page_num, tuple(bbox)) in margin_keys
                    if margin and skip_margins:
                        flush()
                        previous = None
                        stats["repeated_margin_lines_skipped"] += 1
                        stats["text_characters_skipped"] += len(text)
                        continue
                    h = heading_by_key.get(_line_key(page_num, bbox, text))
                    rendered = _render_structured_line(line, stats, markdown)
                    stats["text_lines_exported"] += 1
                    stats["text_characters_exported"] += len(text)
                    if h or margin:
                        flush()
                        previous = None
                        if markdown and h and h["anchor"] not in emitted_anchors:
                            stream.write(
                                f'<a id="{h["anchor"]}"></a>\n\n'
                                + "#" * h["level"]
                                + " "
                                + rendered
                                + "\n\n"
                            )
                            emitted_anchors.add(h["anchor"])
                        else:
                            stream.write(rendered + "\n\n")
                        continue
                    if previous is not None and _paragraph_continues(previous, line, block):
                        stats["paragraph_line_joins"] += 1
                    else:
                        flush()
                    paragraph.append(rendered)
                    previous = line
                flush()
            if markdown:
                for h in headings:
                    if h["page"] == page_num and h["anchor"] not in emitted_anchors:
                        stream.write(f'<a id="{h["anchor"]}"></a>\n\n')
                        emitted_anchors.add(h["anchor"])
                        warnings.append(
                            f"Page {page_num}"
                            f": a heading link falls back to the page end because its "
                            f"text line was not matched."
                        )
        if skip_margins:
            warnings.append(
                f"The skip_repeated_margins option omitted {stats['repeated_margin_lines_skipped']}"
                f" candidate margin lines ({stats['text_characters_skipped']}"
                f" observed characters); review the source for false positives."
            )
        if markdown and not include_images:
            warnings.append("Raster images were excluded by the include_images option.")
        if (
            markdown
            and include_images
            and stats["image_occurrences_seen"] != analysis["image_occurrences"]
        ):
            warnings.append(
                f"Image-info observed {analysis['image_occurrences']}"
                f" occurrences; dictionary extraction exposed {stats['image_occurrences_seen']}"
                f". These observations do not establish visual completeness."
            )
        if markdown:
            stream.write("## Export observations and limitations\n\n")
            for warning in dict.fromkeys(warnings):
                stream.write("- " + _markdown_escape(warning) + "\n")
    return {
        "format": kind,
        "reading_order": reading_order,
        "semantics_verified": False,
        "output_path": str(output),
        "outputs": outputs,
        "self_contained": not bool(stats["images_exported"]),
        "pages_exported": len(analysis["pages"]),
        "source_page_links": len(analysis["pages"]) if markdown else 0,
        "heading_links": len(emitted_anchors),
        "text_characters_exported": stats["text_characters_exported"],
        "text_lines_exported": stats["text_lines_exported"],
        "paragraph_line_joins": stats["paragraph_line_joins"],
        "geometry_inserted_spaces": stats["geometry_inserted_spaces"],
        "images_exported": stats["images_exported"],
        "image_occurrences_detected": analysis["image_occurrences"],
        "image_occurrences_seen": stats["image_occurrences_seen"],
        "image_occurrences_failed": stats["image_occurrences_failed"],
        "superscript_flag_spans": stats["superscript_flag_spans"],
        "geometry_inferred_script_spans": stats["geometry_inferred_script_spans"],
        "repeated_margin_lines_skipped": stats["repeated_margin_lines_skipped"],
        "text_characters_skipped": stats["text_characters_skipped"],
        "naming": analysis["naming"],
        "analysis": analysis,
        "warnings": list(dict.fromkeys(warnings)),
    }


def export_markdown(doc, out_path, original_name, options=None) -> dict:
    """Write structured UTF-8 Markdown with safe sibling PNG/JPEG assets.

    Options: include_images (default True), skip_repeated_margins (default False),
    reading_order (auto, rows or columns; default auto).
    The outputs list includes the Markdown file and every linked image. Preserve
    their relative paths when copying or archiving. No OCR or network is used.
    """
    return _structured_export(doc, out_path, original_name, options, markdown=True)


def export_text(doc, out_path, original_name, options=None) -> dict:
    """Write cleaned UTF-8 text with source page labels and cautious paragraphs.

    Options: skip_repeated_margins (default False), reading_order (auto, rows or
    columns; default auto). Images and font style
    cannot be represented. Characters, including hyphens, are not reconstructed.
    """
    return _structured_export(doc, out_path, original_name, options, markdown=False)
